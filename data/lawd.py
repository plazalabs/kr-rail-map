def selftest():
    cases = [
        (("경기도", "분당구"), "41135"),
        (("서울특별시", "중구"), "11140"),
        (("인천광역시", "중구"), None),   # 원도심/영종으로 갈라짐 — 법정동으로 찾는다
        (("인천광역시", "남구"), "28177"),
        (("경기도", "만악구"), "41171"),
        (("인천광역시", "남돌구"), "28200"),
        (("인천광역시", "부편구"), "28237"),
        (("경기도", "가평군"), "41820"),
        (("경기도", "광주시"), "41610"),
        (("경기도", None), None),
        ((None, "중구"), None),        # 서울·인천 둘 다라 못 정한다
        ((None, "가평군"), "41820"),   # 전국 유일이면 시도 없이도 된다
        (("인청광역시", "연수구"), "28185"),
        (("서울툭별시", "노원구"), "11350"),
        (("경기", "고양시"), None),     # 구가 빠진 주소 — 법정동으로 따로 찾는다
        (("경기도", "화성시"), None),   # 4개 구 코드로 쪼개져 있다 — EXTRA 참고
    ]
    bad = 0
    for (sd, sg), want in cases:
        got = resolve(sd, sg)
        ok = got == want
        bad += 0 if ok else 1
        print(("  ✓ " if ok else "  ✗ ") + "%s/%s → %s" % (sd, sg, got)
              + ("" if ok else "  (기대 %s)" % want))

    # 코드는 유일하고, 이름도 시도 안에서 유일해야 한다.
    assert len(CODE) == len(ROWS) + len(EXTRA), "코드 중복"
    dup = len(BY_NAME) != len(ROWS)
    print(("  ✓ " if not dup else "  ✗ ") + "시도+시군구 조합이 유일")
    bad += 1 if dup else 0
    # EXTRA 는 이름으로 찾을 수 없어야 한다. 이름으로 찾히면 그 이름의
    # 코드가 둘이 되어, 어느 쪽을 골라도 반쪽만 맞는다.
    leak = [r[0] for r in EXTRA if resolve(r[1], r[2]) == r[0]]
    print(("  ✓ " if not leak else "  ✗ ") + "EXTRA 는 이름으로 안 잡힌다")
    bad += 1 if leak else 0
    print("\n%s — %d개 코드, %d개 실패" % ("통과" if not bad else "실패", len(CODE), bad))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(selftest())
