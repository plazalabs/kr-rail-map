def norm_sido(tok):
    """주소 첫 토큰 → 정식 시도 이름. 못 알아보면 None."""
    t = re.sub(r"\s+", "", str(tok or ""))
    if not t:
        return None
    if t in SIDO:
        return SIDO[t]
    # '서울시' '인천' '경기' 처럼 짧게 적은 것
    for short, full in SHORT.items():
        if t.startswith(short):
            # '경기광주' 같은 지명을 시도로 오해하지 않는다 — 뒤에 도/시가 붙어야 한다
            if t == short or t in (short + "시", short + "도") or full.startswith(t) \
                    or t.endswith(("특별시", "광역시", "특별자치시", "도")):
                return full
    # 오타 — '인청광역시', '서울툭별시'. 한 글자까지 고쳐 본다.
    best = _nearest(t, list(SIDO))
    return best


def _lev(a, b):
    if a == b:
        return 0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _nearest(word, pool, maxd=1):
    """한 글자 차이까지 허용해 가장 가까운 후보. 동점이면 포기한다."""
    cands = sorted(((_lev(word, p), p) for p in pool))
    if not cands or cands[0][0] > maxd:
        return None
    if len(cands) > 1 and cands[1][0] == cands[0][0]:
        return None
    return cands[0][1]


def resolve(sido, sgg):
    """(시도, 시군구) → 5자리 코드. 못 찾으면 None.

    시도가 없거나 틀려도 시군구 이름이 전국에서 유일하면 찾는다.
    """
    if not sgg:
        return None
    s = str(sgg).strip()
    sd = norm_sido(sido) if sido else None

    # 1) 정확히 맞는 것
    if sd and (sd, s) in BY_NAME:
        return BY_NAME[(sd, s)]
    if sd and (sd, s) in SGG_ALIAS and SGG_ALIAS[(sd, s)]:
        return BY_NAME.get((sd, SGG_ALIAS[(sd, s)]))

    # 2) 알려진 오타 교정. 여기서 일반적인 '한 글자 차이' 규칙을 쓰면 안 된다 —
    #    '화성시'가 '안성시'로, '광주시'가 '구리시'로 붙을 수 있다. 잘못
    #    붙으면 다른 동네 시세가 그 역에 달라붙는데, 그건 시세가 없는 것보다
    #    훨씬 나쁘다. 실제로 주소데이터에서 확인된 오타만 적어 둔다.
    if sd:
        fixed = SGG_TYPO.get(s)
        if fixed and (sd, fixed) in BY_NAME:
            return BY_NAME[(sd, fixed)]

    # 3) 시도를 모를 때만, 이름이 전국에서 유일하면 채택한다.
    #    시도를 아는데 표에 없으면 포기해야 한다. '인천 중구'를 모른다고
    #    서울 중구로 보내면 인천 역에 서울 시세가 붙는다.
    if not sd and s not in AMBIGUOUS and s in SIDO_OF and len(SIDO_OF[s]) == 1:
        return BY_NAME[(next(iter(SIDO_OF[s])), s)]

    return None


def name_of(code):
    """코드 → (시도, 시군구)."""
    return CODE.get(str(code), (None, None))


def parent_of(code):
    """'성남시 분당구' 의 '성남시'. 구가 없으면 ''."""
    return CODE.get(str(code), ("", "", ""))[2]


def label_of(code):
    """코드 → 사람이 읽는 시군구 이름. '성남시 분당구', '강남구'."""
    _sd, sg, parent = CODE.get(str(code), ("", None, ""))
    if not sg:
        return ""
    return (parent + " " + sg) if parent else sg


def short_sido(sido):
    """'경기도' → '경기' (화면 표시용)."""
    for k, v in SHORT.items():
        if v == sido:
            return k
    return sido or ""


